"""Write thesis/main.tex: the whole thesis in one file, generated from the GIU template folder thesis/overleaf.

Usage: python3 flatten.py <path to bachelor.bbl from the build>
Chapters and appendices are inlined, the BibTeX reference list is embedded, and images fall back to a
labelled box when the figures/ folder is missing, so main.tex also compiles on its own.
"""
import re, sys
from pathlib import Path

SRC = Path(__file__).parent / 'overleaf'
read = lambda f: (SRC / f).read_text().rstrip() + '\n'
img = lambda s: re.sub(r'\\includegraphics(\[[^\]]*\])?\{(?:figures/)?([^}]+)\}',
                       lambda m: '\\thesisimage' + (m.group(1) or '') + '{' + m.group(2) + '}', s)

s = read('bachelor.tex')
def include(m):
    name = m.group(1)
    body = re.sub(r'\\input\{([^}]+)\}', lambda n: '% ---- ' + n.group(1) + '.tex ----\n' + read(n.group(1) + '.tex'), read(name + '.tex'))
    return '\\clearpage\n% ======== ' + name + '.tex ========\n' + body + '\\clearpage\n'
s = re.sub(r'\\include\{([^}]+)\}', include, s)
# figure macros of the template point at images/; keep them but route every image through the fallback
s = img(s.replace('{images/#2}', '{#2}'))
helper = ('% Images: shown when the figures/ folder is next to this file; otherwise a labelled box appears.\n'
          '\\newcommand{\\thesisimage}[2][]{\\IfFileExists{figures/#2}{\\includegraphics[#1]{figures/#2}}'
          '{\\fbox{\\parbox[c][3cm][c]{0.6\\textwidth}{\\centering\\small Image \\texttt{\\detokenize{#2}} not found: upload the \\texttt{figures} folder.}}}}\n')
s = s.replace('\\usepackage{float}', helper + '\\usepackage{float}', 1).replace('\\graphicspath{{figures/}}\n', '')
bib = re.search(r'(?:%[^\n]*\n)*\\bibliographystyle\{[^}]+\}\n\\bibliography\{references\}\n\\addcontentsline\{toc\}\{chapter\}\{References\}\n', s)
assert bib, 'bibliography block not found'
s = s[:bib.start()] + ('% References (IEEE style), generated by BibTeX from overleaf/references.bib.\n'
     '\\renewcommand{\\bibname}{References}\n\\cleardoublepage\\phantomsection\n\\addcontentsline{toc}{chapter}{References}\n'
     + Path(sys.argv[1]).read_text()) + s[bib.end():]
head = ('% GENERATED FILE -- do not edit. The thesis source is the GIU template folder thesis/overleaf/\n'
        '% (main file bachelor.tex). Run `bash thesis/build.sh` to rebuild this file and thesis/thesis-draft.pdf.\n'
        '% This single file contains the whole thesis for pasting into Overleaf; upload figures/ for the images.\n')
(Path(__file__).parent / 'main.tex').write_text(head + s)
print('main.tex written:', len(s.splitlines()), 'lines')
